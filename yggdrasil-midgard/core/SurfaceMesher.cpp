// ─── KD-tree (3D, KNN + radius pruning) ──────────────────────────
struct KDNode {
    int idx;
    int axis;
    int left = -1;
    int right = -1;
};

struct KDTree {
    std::vector<KDNode> nodes;
    const double* pts = nullptr;
    size_t cnt = 0;

    void build(const double* p, size_t n) {
        pts = p;
        cnt = n;
        nodes.clear();
        if (!n) return;
        nodes.reserve(n);
        std::vector<int> ids(n);
        std::iota(ids.begin(), ids.end(), 0);
        buildR(ids.data(), static_cast<int>(n), 0);
    }

    int buildR(int* ids, int n, int depth) {
        if (n <= 0) return -1;
        int axis = depth % 3;
        int m = n / 2;
        std::nth_element(ids, ids + m, ids + n, [&](int a, int b) {
            return pts[a * 3 + axis] < pts[b * 3 + axis];
        });
        int ni = static_cast<int>(nodes.size());
        nodes.push_back({ids[m], axis, -1, -1});
        nodes[ni].left = buildR(ids, m, depth + 1);
        nodes[ni].right = buildR(ids + m + 1, n - m - 1, depth + 1);
        return ni;
    }

    struct Neighbor {
        int idx;
        double d2;
        bool operator<(const Neighbor& o) const { return d2 < o.d2; }
    };

    void knn(const double q[3], int k, double maxR2, std::vector<Neighbor>& out) const {
        out.clear();
        if (nodes.empty()) return;
        knnR(0, q, k, maxR2, out);
    }

    void knnR(int ni, const double q[3], int k, double& maxR2, std::vector<Neighbor>& h) const {
        if (ni < 0) return;
        const KDNode& nd = nodes[ni];
        const double* p = pts + nd.idx * 3;
        double dx = q[0] - p[0];
        double dy = q[1] - p[1];
        double dz = q[2] - p[2];
        double d2 = dx * dx + dy * dy + dz * dz;
        if (d2 < maxR2) {
            if (static_cast<int>(h.size()) < k) {
                h.push_back({nd.idx, d2});
                if (static_cast<int>(h.size()) == k) {
                    std::make_heap(h.begin(), h.end());
                    maxR2 = h.front().d2;
                }
            } else if (d2 < h.front().d2) {
                std::pop_heap(h.begin(), h.end());
                h.back() = {nd.idx, d2};
                std::push_heap(h.begin(), h.end());
                maxR2 = h.front().d2;
            }
        }
        double diff = q[nd.axis] - p[nd.axis];
        int first = diff < 0.0 ? nd.left : nd.right;
        int second = diff < 0.0 ? nd.right : nd.left;
        knnR(first, q, k, maxR2, h);
        if (diff * diff < maxR2) knnR(second, q, k, maxR2, h);
    }
};

// ─── Wendland C2 compact kernel ─────────────────────────────────
inline double wendland(double r) {
    if (r >= 1.0) return 0.0;
    double t = 1.0 - r;
    double t2 = t * t;
    return t2 * t2 * (4.0 * r + 1.0);
}

